    private static readonly byte[] Unknown = { 0x7F, 0x41, 0x41, 0x41, 0x7F };

    public static byte[] Glyph(char c) =>
        Glyphs.TryGetValue(char.ToUpperInvariant(c), out var g) ? g : Unknown;

    /// <summary>A character centred in a full 5-column cell, for a single character module.</summary>
    public static byte[] Cell(char c)
    {
        var glyph = Glyph(c);
        var cell = new byte[Width];
        int start = (Width - glyph.Length) / 2;
        for (int i = 0; i < glyph.Length && start + i < Width; i++)
            cell[start + i] = glyph[i];
        return cell;
    }
